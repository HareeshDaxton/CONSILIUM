"""Screening report document (AGENTS.md §15/§17, paper Fig. 2 "Final Clinical Report").

ONE structured document is built here and rendered three ways — on screen
(JSON), PDF and Word — so the exported file always says exactly what the
review UI shows. The report's state (approved / draft / unverified /
rejected) is decided HERE, server-side, from the case status and the stored
draft; the UI never infers it (I-4).

Content rules:
  - Numbers come only from the CADResult and the case's fact sheet (I-1);
    every finding lists the evidence it cites (I-3).
  - Unapproved drafts are labelled as such on every rendering, with the
    critic's open issues when UNVERIFIED; only an APPROVED* report carries
    clinician attribution (I-4).
  - Screening-support wording on every page (I-12).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict

from consilium.schemas.agents import DirectorDraft
from consilium.schemas.audit import Issue
from consilium.schemas.context import Fact
from consilium.schemas.enums import CaseStatus, FactSource, Laterality
from consilium.schemas.vision import CADResult

__all__ = [
    "Approval",
    "EvidenceItem",
    "MetricRow",
    "ReportDisagreement",
    "ReportDocument",
    "ReportFinding",
    "ReportRecommendation",
    "build_report_document",
    "format_value",
]

SCREENING_FOOTER = (
    "Screening support only — not a diagnosis. Generated by CONSILIUM (research prototype); "
    "clinical decisions rest with the attributed clinician."
)

ReportState = Literal["approved", "draft", "unverified", "rejected"]

_STATE_TEXT: dict[ReportState, tuple[str, str]] = {
    "approved": (
        "Clinician-approved report",
        "Reviewed and signed by the attributed clinician.",
    ),
    "draft": (
        "DRAFT — awaiting clinician review",
        "Passed the deterministic verifier and the critic. Not a final report until a "
        "clinician (other than the submitter) reviews and signs it.",
    ),
    "unverified": (
        "UNVERIFIED DRAFT — critic did not approve",
        "Not for clinical use. A clinician must correct every flagged claim and sign "
        "before this can become a report.",
    ),
    "rejected": (
        "REJECTED by a clinician",
        "This draft was rejected during clinical review and must not be used.",
    ),
}

_EYE = {
    Laterality.OD: "Right eye (OD)",
    Laterality.OS: "Left eye (OS)",
    Laterality.UNKNOWN: "Eye not specified",
}


class _Doc(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class MetricRow(_Doc):
    label: str
    value: str
    note: str | None = None


class EvidenceItem(_Doc):
    fact_id: str
    label: str
    value: str


class ReportFinding(_Doc):
    claim_id: str
    text: str
    evidence: tuple[EvidenceItem, ...]
    source_roles: tuple[str, ...]
    flagged: tuple[str, ...] = ()  # open critic issues on this claim (unverified drafts)


class ReportDisagreement(_Doc):
    topic: str
    positions: tuple[tuple[str, str], ...]
    resolution: str


class ReportRecommendation(_Doc):
    text: str
    triggered_by: tuple[str, ...]


class ReportDocument(_Doc):
    title: str
    case_id: str
    eye: str
    created_at: datetime | None
    generated_at: datetime
    state: ReportState
    state_label: str
    state_detail: str
    approved_by: str | None = None
    approved_at: datetime | None = None
    version: int | None = None
    reason_codes: tuple[str, ...] = ()
    draft_revision: int
    image_findings: tuple[MetricRow, ...]
    note_facts: tuple[MetricRow, ...]
    impression: str
    findings: tuple[ReportFinding, ...]
    disagreements: tuple[ReportDisagreement, ...]
    recommendations: tuple[ReportRecommendation, ...]
    limitations: tuple[str, ...]
    open_issues: tuple[str, ...]
    model_info: tuple[MetricRow, ...]
    footer: str = SCREENING_FOOTER


@dataclass(frozen=True)
class Approval:
    approved_by: str
    approved_at: datetime
    version: int
    reason_codes: tuple[str, ...]
    draft_revision: int
    report: DirectorDraft


def format_value(value: object, unit: str | None = None) -> str:
    if isinstance(value, bool):
        text = "yes" if value else "no"
    elif isinstance(value, float):
        text = f"{value:.3f}".rstrip("0").rstrip(".") if value % 1 else f"{value:.0f}"
    elif isinstance(value, tuple | list):
        text = ", ".join(str(v) for v in value) or "none"
    else:
        text = str(value)
    return f"{text} {unit}" if unit else text


def _short_version(version: str) -> str:
    """'org/model@<40-hex>+mlflow:x' -> 'org/model @ <12-hex>' for readability."""
    model, _, rest = version.partition("@")
    revision = rest.split("+", 1)[0]
    return f"{model} @ {revision[:12]}" if revision else model


def _image_findings(cad: CADResult | None) -> tuple[MetricRow, ...]:
    if cad is None:
        return ()
    flags = ", ".join(f.value.replace("_", " ") for f in cad.quality.flags) or "none"
    return (
        MetricRow(label="Screening tier", value=cad.classifier.tier.value.capitalize()),
        MetricRow(
            label="Glaucoma probability (calibrated)",
            value=f"{cad.classifier.p_calibrated:.2f}",
            note="SwinV2 classifier output after in-repo calibration",
        ),
        MetricRow(
            label="Vertical cup-to-disc ratio",
            value=f"{cad.cdr.vertical:.3f}",
            note="Cup height / disc height from the SegFormer masks",
        ),
        MetricRow(
            label="Area-based cup-to-disc ratio",
            value=f"{cad.cdr.area_based:.3f}",
            note="Secondary: sqrt(cup area / disc area)",
        ),
        MetricRow(label="Image quality", value=f"{cad.quality.score:.2f}", note=f"Flags: {flags}"),
        MetricRow(
            label="Mask quality check",
            value="passed" if cad.mask_qc.ok else "FAILED",
            note=None if cad.mask_qc.ok else "Treat the measurements with caution",
        ),
    )


def build_report_document(
    *,
    case_id: str,
    case_status: CaseStatus,
    laterality: Laterality,
    created_at: datetime | None,
    generated_at: datetime,
    cad: CADResult | None,
    facts: tuple[Fact, ...],
    draft: DirectorDraft,
    draft_revision: int,
    unverified: bool,
    open_issues: tuple[Issue, ...],
    approval: Approval | None,
    calibration_fitted: bool,
) -> ReportDocument:
    """Assemble the document. ``approval`` is given only for APPROVED* cases."""
    if approval is not None:
        state: ReportState = "approved"
        content, revision = approval.report, approval.draft_revision
    else:
        state = (
            "rejected"
            if case_status == CaseStatus.REJECTED
            else ("unverified" if unverified else "draft")
        )
        content, revision = draft, draft_revision
    label, detail = _STATE_TEXT[state]

    by_id = {f.id: f for f in facts}

    def evidence(ids: tuple[str, ...]) -> tuple[EvidenceItem, ...]:
        items = []
        for fid in ids:
            fact = by_id.get(fid)
            items.append(
                EvidenceItem(
                    fact_id=fid,
                    label=fact.label if fact else fid,
                    value=format_value(fact.value, fact.unit) if fact else "not in fact sheet",
                )
            )
        return tuple(items)

    issues_by_claim: dict[str, list[str]] = {}
    general_issues: list[str] = []
    shown_issues = open_issues if state == "unverified" else ()
    for issue in shown_issues:
        text = f"{issue.type.value.replace('_', ' ')}: {issue.detail}"
        if issue.claim_id:
            issues_by_claim.setdefault(issue.claim_id, []).append(text)
        else:
            general_issues.append(text)

    model_info = [
        MetricRow(
            label="Classifier (SwinV2)",
            value=_short_version(cad.classifier.model_version) if cad else "not available",
        ),
        MetricRow(
            label="Segmenter (SegFormer)",
            value=_short_version(cad.segmenter_version) if cad else "not available",
        ),
        MetricRow(
            label="Probability calibration",
            value="fitted" if calibration_fitted else "not yet fitted (identity)",
        ),
    ]

    return ReportDocument(
        title="Glaucoma Screening Support Report",
        case_id=case_id,
        eye=_EYE[laterality],
        created_at=created_at,
        generated_at=generated_at,
        state=state,
        state_label=label,
        state_detail=detail,
        approved_by=approval.approved_by if approval else None,
        approved_at=approval.approved_at if approval else None,
        version=approval.version if approval else None,
        reason_codes=approval.reason_codes if approval else (),
        draft_revision=revision,
        image_findings=_image_findings(cad),
        note_facts=tuple(
            MetricRow(label=f.label, value=format_value(f.value, f.unit))
            for f in facts
            if f.source == FactSource.NOTE and not f.id.startswith("note.caveat")
        ),
        impression=content.impression,
        findings=tuple(
            ReportFinding(
                claim_id=c.id,
                text=c.text,
                evidence=evidence(c.evidence_refs),
                source_roles=tuple(r.value for r in c.source_roles),
                flagged=tuple(issues_by_claim.get(c.id, ())),
            )
            for c in content.claims
        ),
        disagreements=tuple(
            ReportDisagreement(
                topic=d.topic,
                positions=tuple((role.value, text) for role, text in d.positions),
                resolution=d.resolution,
            )
            for d in content.disagreements
        ),
        recommendations=tuple(
            ReportRecommendation(
                text=r.text, triggered_by=tuple(e.label for e in evidence(r.triggered_by))
            )
            for r in content.recommendations
        ),
        limitations=content.limitations,
        open_issues=tuple(general_issues),
        model_info=tuple(model_info),
    )
