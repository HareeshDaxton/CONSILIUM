"""Frozen, versioned eval case sets (plan Section 13.1; AGENTS.md §19.3).

A case set is a JSON manifest of ``EvalCase``s. Each case carries its
**recorded** ``CADResult`` (held constant across S1-S4 — the ablation varies
only the architecture, never the vision output; SKILLS.md ablation-run step 1)
plus the already-structured clinical note. The eval harness never calls the
vision endpoint while running stages.

Versioning: ``dataset_version`` is the sha256 of the manifest file bytes, so
any edit to any case is a new dataset version and shows up in every stored
run's provenance. The smoke manifest is generated by
``eval/fixtures.py:smoke_manifest`` and committed next to this module
(``data/smoke_v1.json``); a unit test checks it never drifts from its
generator. The full frozen set lives under the gitignored repo ``data/``
(DVC-tracked) and is produced by ``fixtures.record_cases`` from real endpoint
responses — never hand-edited.

Fixtures contain no real patient data (§20): smoke cases are synthetic, and
full-set notes are synthetic structured notes paired with dataset images.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Literal

from pydantic import Field

from consilium.schemas.base import Strict
from consilium.schemas.note import ClinicalNote, NoteExtraction
from consilium.schemas.vision import CADResult

EVAL_DATA_DIR = Path(__file__).resolve().parent / "data"
SMOKE_MANIFEST_PATH = EVAL_DATA_DIR / "smoke_v1.json"
# Full frozen set: gitignored repo data/ (DVC pointer committed separately).
FULL_MANIFEST_PATH = Path(__file__).resolve().parents[3] / "data" / "eval" / "full_v1.json"

Split = Literal["dev", "holdout"]


class EvalCase(Strict):
    """One frozen eval case: recorded CAD output + structured note."""

    case_id: str = Field(min_length=1, max_length=64)  # opaque, never a patient ID (I-6)
    split: Split = "dev"
    cad: CADResult
    note: ClinicalNote | None = None
    extraction: NoteExtraction | None = None
    # Where the CADResult came from: "synthetic" (smoke) or
    # "recorded:<endpoint_revision>" (full set, recorded once, then frozen).
    cad_provenance: str = Field(min_length=1)
    # Curated disagreement set (§19.2 minority-opinion preservation): the
    # configured disagreement topics on which roles SHOULD disagree here.
    curated_disagreement_topics: tuple[str, ...] = ()


class CaseManifest(Strict):
    """A frozen case set. Identity = ``dataset_id`` + file sha256."""

    dataset_id: str = Field(min_length=1)
    description: str
    cases: tuple[EvalCase, ...] = Field(min_length=1)

    def select(self, split: Split | None = None) -> tuple[EvalCase, ...]:
        """Cases of one split (None = all), in manifest order."""
        return tuple(c for c in self.cases if split is None or c.split == split)


class LoadedManifest(Strict):
    manifest: CaseManifest
    dataset_version: str  # sha256 of the manifest bytes


def manifest_bytes(manifest: CaseManifest) -> bytes:
    """Canonical serialization (stable key order, trailing newline)."""
    return (manifest.model_dump_json(indent=2) + "\n").encode("utf-8")


def load_manifest(path: Path) -> LoadedManifest:
    """Load + validate a manifest; fail loudly on duplicates (§19.3 rigor)."""
    raw = path.read_bytes()
    manifest = CaseManifest.model_validate_json(raw)
    ids = [c.case_id for c in manifest.cases]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise ValueError(f"manifest {path.name} has duplicate case IDs: {dupes}")
    return LoadedManifest(manifest=manifest, dataset_version=hashlib.sha256(raw).hexdigest())
