"""OpenAI implementation of LLMClient (ARCHITECTURE.md §5.7).

The ONLY module in src/ that imports the OpenAI SDK (import-linter contract
``openai-only-in-llm``). Structured output is bound to the Pydantic response
model: the strict JSON schema is generated by the SDK's own
``type_to_response_format_param`` (the exact function ``parse`` uses —
verified against the pinned SDK, openai 3.27.0; re-check when upgrading) and
the reply is validated with ``response_model.model_validate_json`` (the SDK's
JSON-mode parse path), so Pydantic strict validation stays the gate (I-8).

Wire adaptation (found by the Phase 13 live eval): OpenAI strict mode rejects
JSON-Schema tuple arrays (``prefixItems``, e.g. ``Disagreement.positions:
tuple[tuple[Role, str], ...]`` — "array schema missing items"), which made
every live Director/single-agent call fail with a 400. ``_adapt_tuple_arrays``
rewrites ONLY such nodes into ``items: {anyOf: [...]}`` for the request; the
response is still validated against the unchanged strict model (exact arity
and types), and a mismatch goes through the normal bounded repair loop. Schemas
without tuples are sent byte-for-byte as the SDK generates them.

Error mapping (SKILLS.md llm-client-and-fakes):
  - timeout / 429 / 5xx / connection        → LLMTransient (retryable)
  - refusal / content-filter finish         → AgentFailure(LLM_REFUSAL) — never retried
  - validation failure / truncated / empty  → ModelOutputInvalid (bounded repair)
  - other 4xx APIStatusError                → AgentFailure(LLM_REQUEST_REJECTED)

Model IDs come from config as dated snapshots (AGENTS.md §6) — never floating
aliases. Message bodies are never logged (I-6/I-7).
"""

from __future__ import annotations

import copy
import time
from typing import Any, TypeVar, cast

import openai
from openai import AsyncOpenAI
from openai.lib._parsing._completions import type_to_response_format_param
from openai.types.chat import ChatCompletionMessageParam
from openai.types.chat.completion_create_params import ResponseFormat
from pydantic import BaseModel, ValidationError

from consilium.core.errors import AgentFailure
from consilium.llm.client import (
    ChatMessage,
    LLMTransient,
    ModelOutputInvalid,
    ParsedResponse,
)

T = TypeVar("T", bound=BaseModel)

_TRANSIENT_ERRORS = (
    openai.APITimeoutError,
    openai.RateLimitError,
    openai.InternalServerError,
    openai.APIConnectionError,
)


def _adapt_tuple_arrays(node: Any) -> None:
    """In place: ``prefixItems`` tuple arrays → ``items: {anyOf: [...]}``."""
    if isinstance(node, dict):
        if "prefixItems" in node:
            variants: list[Any] = []
            for item in node.pop("prefixItems"):
                if item not in variants:
                    variants.append(item)
            node.pop("minItems", None)
            node.pop("maxItems", None)
            node["items"] = variants[0] if len(variants) == 1 else {"anyOf": variants}
        for value in node.values():
            _adapt_tuple_arrays(value)
    elif isinstance(node, list):
        for value in node:
            _adapt_tuple_arrays(value)


def response_format_for(response_model: type[BaseModel]) -> dict[str, Any]:
    """The SDK's strict json_schema response format, tuple arrays adapted."""
    raw = type_to_response_format_param(response_model)  # json_schema for a model type
    fmt: dict[str, Any] = copy.deepcopy(cast("dict[str, Any]", raw))
    _adapt_tuple_arrays(fmt)
    return fmt


class OpenAILLMClient:
    """LLMClient backed by the OpenAI Chat Completions structured-output API."""

    def __init__(self, api_key: str, *, base_url: str | None = None) -> None:
        self._client = AsyncOpenAI(api_key=api_key, base_url=base_url)

    async def generate(
        self,
        messages: list[ChatMessage],
        response_model: type[T],
        *,
        model: str,
        temperature: float,
        max_output_tokens: int,
        timeout_s: float,
        tags: dict[str, str],
    ) -> ParsedResponse[T]:
        started = time.monotonic()
        try:
            completion = await self._client.chat.completions.create(
                model=model,
                messages=cast(
                    "list[ChatCompletionMessageParam]",
                    [m.to_param() for m in messages],
                ),
                response_format=cast("ResponseFormat", response_format_for(response_model)),
                temperature=temperature,
                max_completion_tokens=max_output_tokens,
                timeout=timeout_s,
            )
        except _TRANSIENT_ERRORS as exc:
            raise LLMTransient(type(exc).__name__) from exc
        except openai.APIStatusError as exc:
            raise AgentFailure(
                "LLM_REQUEST_REJECTED", detail=f"api status {exc.status_code}"
            ) from exc
        latency_ms = (time.monotonic() - started) * 1000.0

        choice = completion.choices[0]
        if choice.finish_reason == "content_filter":
            raise AgentFailure("LLM_REFUSAL", detail="content-filter finish")
        if choice.message.refusal is not None:
            raise AgentFailure("LLM_REFUSAL", detail="model refusal")
        if choice.finish_reason == "length":
            raise ModelOutputInvalid("output truncated at the token limit")
        content = choice.message.content
        if not content:
            raise ModelOutputInvalid("no content returned for the response schema")
        try:
            data = response_model.model_validate_json(content)
        except ValidationError as exc:
            raise ModelOutputInvalid(str(exc)) from exc

        usage = completion.usage
        return ParsedResponse(
            data=data,
            model=model,
            prompt_version=tags.get("prompt_version"),
            input_tokens=usage.prompt_tokens if usage is not None else 0,
            output_tokens=usage.completion_tokens if usage is not None else 0,
            latency_ms=latency_ms,
            attempts=1,
        )
